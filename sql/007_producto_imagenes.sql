-- ETERNA FRAGANCIA - Imágenes múltiples por producto
-- Requiere 004_producto_variantes.sql para reutilizar public.es_admin().
-- No modifica productos, variantes ni archivos existentes en Storage.

begin;

create table if not exists public.producto_imagenes (
    id bigint generated by default as identity primary key,
    producto_id bigint not null references public.productos(id) on delete cascade,
    imagen_url text not null,
    imagen_storage_path text,
    orden integer not null default 0 check (orden >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists producto_imagenes_producto_orden_idx
    on public.producto_imagenes (producto_id, orden, id);

alter table public.producto_imagenes enable row level security;

revoke all on table public.producto_imagenes from anon;
revoke all on table public.producto_imagenes from authenticated;
grant select on table public.producto_imagenes to anon, authenticated;
grant insert, update, delete on table public.producto_imagenes to authenticated;

drop policy if exists "Public can read product images" on public.producto_imagenes;
create policy "Public can read product images"
    on public.producto_imagenes
    for select
    to anon, authenticated
    using (true);

drop policy if exists "Admins can insert product images" on public.producto_imagenes;
create policy "Admins can insert product images"
    on public.producto_imagenes
    for insert
    to authenticated
    with check (public.es_admin());

drop policy if exists "Admins can update product images" on public.producto_imagenes;
create policy "Admins can update product images"
    on public.producto_imagenes
    for update
    to authenticated
    using (public.es_admin())
    with check (public.es_admin());

drop policy if exists "Admins can delete product images" on public.producto_imagenes;
create policy "Admins can delete product images"
    on public.producto_imagenes
    for delete
    to authenticated
    using (public.es_admin());

commit;
