-- ETERNA FRAGANCIA - Pedidos persistidos y confirmación segura
-- Preparado para revisión. No ejecutar automáticamente.
-- Requiere 004_producto_variantes.sql y 005_confirmar_pedidos_stock.sql.
-- Usa la autorización existente public.es_admin().

create table if not exists public.pedidos (
    id bigint generated by default as identity primary key,
    order_key text not null unique,
    creado_at timestamptz not null default now(),
    actualizado_at timestamptz not null default now(),
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'confirmado', 'preparando', 'entregado', 'cancelado')),
    customer_name text not null,
    customer_email text not null,
    customer_phone text not null,
    payment_method text not null,
    notes text not null default '',
    subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
    total numeric(12, 2) not null default 0 check (total >= 0),
    confirmado_at timestamptz,
    confirmado_por uuid references auth.users(id)
);

create table if not exists public.pedido_items (
    id bigint generated by default as identity primary key,
    pedido_id bigint not null references public.pedidos(id) on delete cascade,
    producto_id bigint not null references public.productos(id) on delete restrict,
    variante_id bigint references public.producto_variantes(id) on delete restrict,
    producto_nombre text not null,
    aroma text,
    cantidad integer not null check (cantidad > 0),
    precio_unitario numeric(12, 2) not null check (precio_unitario >= 0),
    subtotal numeric(12, 2) not null check (subtotal >= 0)
);

create index if not exists idx_pedidos_estado_creado_at
    on public.pedidos (estado, creado_at desc);

create index if not exists idx_pedido_items_pedido_id
    on public.pedido_items (pedido_id);

alter table public.pedidos enable row level security;
alter table public.pedido_items enable row level security;

revoke all on table public.pedidos, public.pedido_items from public, anon, authenticated;
grant select on table public.pedidos, public.pedido_items to authenticated;
grant usage, select on sequence public.pedidos_id_seq, public.pedido_items_id_seq to authenticated;

do $$
begin
    drop policy if exists "Administrators can read orders" on public.pedidos;
    create policy "Administrators can read orders"
        on public.pedidos for select to authenticated
        using ((select public.es_admin()));

    drop policy if exists "Administrators can read order items" on public.pedido_items;
    create policy "Administrators can read order items"
        on public.pedido_items for select to authenticated
        using ((select public.es_admin()));
end $$;

-- Crea el pedido pendiente y calcula precio/subtotal desde public.productos.
-- El navegador solo envía identificadores y cantidades; nunca fija precios.
create or replace function public.create_pending_order(
    p_order_key text,
    p_customer_name text,
    p_customer_email text,
    p_customer_phone text,
    p_payment_method text,
    p_notes text,
    p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    item jsonb;
    v_order_id bigint;
    v_existing_id bigint;
    v_product_id bigint;
    v_variant_id bigint;
    v_quantity integer;
    v_product_name text;
    v_aroma text;
    v_price numeric(12, 2);
    v_product_active boolean;
    v_stock integer;
    v_variant_stock integer;
    v_has_variants boolean;
    v_requested_before integer;
    v_line_subtotal numeric(12, 2);
    v_subtotal numeric(12, 2) := 0;
begin
    if nullif(trim(p_order_key), '') is null then
        raise exception 'El identificador del pedido es obligatorio.' using errcode = '22023';
    end if;
    if nullif(trim(p_customer_name), '') is null
       or nullif(trim(p_customer_email), '') is null
       or nullif(trim(p_customer_phone), '') is null then
        raise exception 'Los datos del cliente son obligatorios.' using errcode = '22023';
    end if;
    if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'El pedido no contiene productos válidos.' using errcode = '22023';
    end if;

    p_order_key := trim(p_order_key);

    insert into public.pedidos (
        order_key, customer_name, customer_email, customer_phone,
        payment_method, notes
    )
    values (
        p_order_key, trim(p_customer_name), trim(p_customer_email),
        trim(p_customer_phone), trim(p_payment_method), coalesce(p_notes, '')
    )
    on conflict (order_key) do nothing
    returning id into v_order_id;

    if v_order_id is null then
        select id, subtotal, total
          into v_existing_id, v_subtotal, v_line_subtotal
          from public.pedidos
         where order_key = p_order_key;
        return jsonb_build_object(
            'id', v_existing_id,
            'order_key', p_order_key,
            'subtotal', v_subtotal,
            'total', v_line_subtotal,
            'already_created', true
        );
    end if;

    for item in select value from jsonb_array_elements(p_items)
    loop
        v_product_id := nullif(item->>'product_id', '')::bigint;
        v_variant_id := nullif(item->>'variant_id', '')::bigint;
        v_quantity := nullif(item->>'quantity', '')::integer;

        if v_product_id is null or v_quantity is null or v_quantity <= 0 then
            raise exception 'El pedido contiene una cantidad o producto inválido.' using errcode = '22023';
        end if;

        select p.nombre, p.precio, p.stock, p.estado,
               exists (select 1 from public.producto_variantes pv where pv.producto_id = p.id and pv.stock > 0)
          into v_product_name, v_price, v_stock, v_product_active, v_has_variants
          from public.productos p
         where p.id = v_product_id;

        if not found then
            raise exception 'El producto seleccionado ya no existe.' using errcode = 'P0002';
        end if;

        if not coalesce(v_product_active, false) then
            raise exception 'El producto seleccionado no está disponible.' using errcode = '22023';
        end if;

        if v_variant_id is not null then
            select pv.aroma, pv.stock
              into v_aroma, v_variant_stock
              from public.producto_variantes pv
             where pv.id = v_variant_id
               and pv.producto_id = v_product_id;
            if not found then
                raise exception 'La variante seleccionada ya no existe.' using errcode = 'P0002';
            end if;
            if v_variant_stock < v_quantity then
                raise exception 'Stock insuficiente para la variante seleccionada.' using errcode = 'P0001';
            end if;
            select coalesce(sum(cantidad), 0)
              into v_requested_before
              from public.pedido_items
             where pedido_id = v_order_id
               and variante_id = v_variant_id;
            if v_variant_stock < v_requested_before + v_quantity then
                raise exception 'La cantidad total solicitada supera el stock de la variante.' using errcode = 'P0001';
            end if;
        elsif v_has_variants then
            raise exception 'El producto requiere una variante de aroma.' using errcode = '22023';
        elsif v_stock < v_quantity then
            raise exception 'Stock insuficiente para el producto seleccionado.' using errcode = 'P0001';
        else
            select coalesce(sum(cantidad), 0)
              into v_requested_before
              from public.pedido_items
             where pedido_id = v_order_id
               and producto_id = v_product_id
               and variante_id is null;
            if v_stock < v_requested_before + v_quantity then
                raise exception 'La cantidad total solicitada supera el stock del producto.' using errcode = 'P0001';
            end if;
        end if;

        v_line_subtotal := round(v_price * v_quantity, 2);
        v_subtotal := v_subtotal + v_line_subtotal;

        insert into public.pedido_items (
            pedido_id, producto_id, variante_id, producto_nombre, aroma,
            cantidad, precio_unitario, subtotal
        )
        values (
            v_order_id, v_product_id, v_variant_id, v_product_name, v_aroma,
            v_quantity, v_price, v_line_subtotal
        );
    end loop;

    update public.pedidos
       set subtotal = v_subtotal,
           total = v_subtotal
     where id = v_order_id;

    return jsonb_build_object(
        'id', v_order_id,
        'order_key', p_order_key,
        'subtotal', v_subtotal,
        'total', v_subtotal,
        'already_created', false
    );
end;
$$;

revoke all on function public.create_pending_order(text, text, text, text, text, text, jsonb)
    from public, anon, authenticated;
grant execute on function public.create_pending_order(text, text, text, text, text, text, jsonb)
    to anon, authenticated;

-- Confirma exclusivamente las líneas persistidas del pedido.
create or replace function public.confirm_order_stock(p_order_key text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_order public.pedidos%rowtype;
    line record;
    v_variant_stock integer;
    v_product_stock integer;
    v_has_variants boolean;
    v_user_id uuid := auth.uid();
    v_snapshot jsonb;
begin
    if v_user_id is null or not public.es_admin() then
        raise exception 'La confirmación requiere permisos de administrador.' using errcode = '42501';
    end if;

    select * into v_order
      from public.pedidos
     where order_key = trim(p_order_key)
     for update;

    if not found then
        raise exception 'El pedido no existe en Supabase.' using errcode = 'P0002';
    end if;
    if v_order.estado = 'confirmado' then
        return jsonb_build_object('confirmed', false, 'already_confirmed', true);
    end if;
    if v_order.estado <> 'pendiente' then
        raise exception 'Solo se pueden confirmar pedidos pendientes.' using errcode = '22023';
    end if;

    select jsonb_agg(jsonb_build_object(
        'product_id', producto_id,
        'variant_id', variante_id,
        'quantity', cantidad
    ) order by id)
      into v_snapshot
      from public.pedido_items
     where pedido_id = v_order.id;

    if v_snapshot is null then
        raise exception 'El pedido no tiene líneas guardadas.' using errcode = '22023';
    end if;

    for line in
        select * from public.pedido_items where pedido_id = v_order.id order by id
    loop
        if line.variante_id is not null then
            select stock into v_variant_stock
              from public.producto_variantes
             where id = line.variante_id
               and producto_id = line.producto_id
             for update;
            if not found then
                raise exception 'La variante del pedido ya no existe.' using errcode = 'P0002';
            end if;
            if v_variant_stock < line.cantidad then
                raise exception 'Stock insuficiente para una variante del pedido.' using errcode = 'P0001';
            end if;
            update public.producto_variantes
               set stock = stock - line.cantidad,
                   updated_at = now()
             where id = line.variante_id;
        else
            select exists (
                select 1 from public.producto_variantes
                 where producto_id = line.producto_id
                   and stock > 0
            ) into v_has_variants;
            if v_has_variants then
                raise exception 'El pedido no tiene una variante para un producto que la requiere.' using errcode = '22023';
            end if;
            select stock into v_product_stock
              from public.productos
             where id = line.producto_id
             for update;
            if not found then
                raise exception 'El producto del pedido ya no existe.' using errcode = 'P0002';
            end if;
            if v_product_stock < line.cantidad then
                raise exception 'Stock insuficiente para un producto del pedido.' using errcode = 'P0001';
            end if;
            update public.productos
               set stock = stock - line.cantidad
             where id = line.producto_id;
        end if;
    end loop;

    update public.pedidos
       set estado = 'confirmado', confirmado_at = now(), confirmado_por = v_user_id,
           actualizado_at = now()
     where id = v_order.id;

    insert into public.pedido_confirmaciones (order_key, items, confirmado_por)
    values (v_order.order_key, v_snapshot, v_user_id)
    on conflict (order_key) do nothing;

    return jsonb_build_object('confirmed', true, 'already_confirmed', false);
end;
$$;

revoke all on function public.confirm_order_stock(text) from public, anon, authenticated;
grant execute on function public.confirm_order_stock(text) to authenticated;

create or replace function public.update_order_status(
    p_order_key text,
    p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_order public.pedidos%rowtype;
begin
    if not public.es_admin() then
        raise exception 'La actualización requiere permisos de administrador.' using errcode = '42501';
    end if;
    if p_status not in ('pendiente', 'preparando', 'entregado', 'cancelado') then
        raise exception 'Estado de pedido no válido para esta operación.' using errcode = '22023';
    end if;

    select * into v_order from public.pedidos
     where order_key = trim(p_order_key) for update;
    if not found then
        raise exception 'El pedido no existe en Supabase.' using errcode = 'P0002';
    end if;
    if v_order.estado = 'pendiente' and p_status not in ('pendiente', 'cancelado') then
        raise exception 'El pedido debe confirmarse antes de pasar a preparación o entrega.' using errcode = '22023';
    end if;
    if v_order.estado = 'confirmado' and p_status not in ('preparando', 'entregado') then
        raise exception 'Un pedido confirmado no puede volver a pendiente ni cancelarse sin devolver stock.' using errcode = '22023';
    end if;
    if v_order.estado = 'preparando' and p_status not in ('preparando', 'entregado') then
        raise exception 'Un pedido en preparación no puede retroceder ni cancelarse sin devolver stock.' using errcode = '22023';
    end if;
    if v_order.estado in ('entregado', 'cancelado') and p_status <> v_order.estado then
        raise exception 'El estado final del pedido no puede modificarse sin una operación específica.' using errcode = '22023';
    end if;

    update public.pedidos
       set estado = p_status, actualizado_at = now()
     where id = v_order.id;
    return jsonb_build_object('updated', true, 'status', p_status);
end;
$$;

revoke all on function public.update_order_status(text, text) from public, anon, authenticated;
grant execute on function public.update_order_status(text, text) to authenticated;

-- Elimina una única línea de un pedido pendiente o cancelado y recalcula sus importes.
-- No modifica productos, variantes ni stock.
create or replace function public.remove_order_item(
    p_order_id bigint,
    p_item_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_order public.pedidos%rowtype;
    v_subtotal numeric(12, 2);
begin
    if not public.es_admin() then
        raise exception 'La eliminación requiere permisos de administrador.' using errcode = '42501';
    end if;

    select * into v_order
      from public.pedidos
     where id = p_order_id
     for update;

    if not found then
        raise exception 'El pedido no existe en Supabase.' using errcode = 'P0002';
    end if;
    if v_order.estado not in ('pendiente', 'cancelado') then
        raise exception 'Solo se pueden modificar pedidos pendientes o cancelados.' using errcode = '22023';
    end if;
    if not exists (
        select 1 from public.pedido_items
         where id = p_item_id and pedido_id = p_order_id
    ) then
        raise exception 'El producto no pertenece a este pedido.' using errcode = 'P0002';
    end if;

    delete from public.pedido_items
     where id = p_item_id and pedido_id = p_order_id;

    if not exists (
        select 1 from public.pedido_items where pedido_id = p_order_id
    ) then
        delete from public.pedidos where id = p_order_id;

        return jsonb_build_object(
            'removed', true,
            'order_deleted', true,
            'empty', true,
            'subtotal', 0,
            'total', 0
        );
    end if;

    select coalesce(sum(subtotal), 0)::numeric(12, 2)
      into v_subtotal
      from public.pedido_items
     where pedido_id = p_order_id;

    update public.pedidos
       set subtotal = v_subtotal,
           total = v_subtotal,
           actualizado_at = now()
     where id = p_order_id;

    return jsonb_build_object(
        'removed', true,
        'order_deleted', false,
        'empty', not exists (select 1 from public.pedido_items where pedido_id = p_order_id),
        'subtotal', v_subtotal,
        'total', v_subtotal
    );
end;
$$;

revoke all on function public.remove_order_item(bigint, bigint) from public, anon, authenticated;
grant execute on function public.remove_order_item(bigint, bigint) to authenticated;
