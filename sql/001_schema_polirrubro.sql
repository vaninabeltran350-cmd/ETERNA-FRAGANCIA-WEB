-- ETERNA FRAGANCIA - Propuesta inicial de esquema Supabase Database
-- Cambio 1: estructura de categorías, productos y configuración.
--
-- Este archivo es preparatorio. No se ejecuta automáticamente y no contiene
-- una migración de datos desde localStorage ni desde data/productos.json.

CREATE TABLE IF NOT EXISTS public.categorias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    slug text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.productos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id bigint NOT NULL REFERENCES public.categorias(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    nombre text NOT NULL,
    descripcion text NOT NULL DEFAULT '',
    precio numeric(12, 2) NOT NULL DEFAULT 0
        CHECK (precio >= 0),
    stock integer NOT NULL DEFAULT 0
        CHECK (stock >= 0),
    imagen_url text,
    imagen_storage_path text,
    destacado boolean NOT NULL DEFAULT false,
    estado text NOT NULL DEFAULT 'disponible'
        CHECK (estado IN ('disponible', 'agotado')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS productos_categoria_id_idx
    ON public.productos (categoria_id);

CREATE INDEX IF NOT EXISTS productos_estado_destacado_idx
    ON public.productos (estado, destacado);

CREATE TABLE IF NOT EXISTS public.configuracion (
    id smallint PRIMARY KEY DEFAULT 1
        CHECK (id = 1),
    store_name text NOT NULL DEFAULT 'R&B',
    store_description text NOT NULL DEFAULT '',
    store_logo text,
    whatsapp_number text,
    instagram_username text,
    store_address text,
    store_hours text,
    bank_alias text,
    bank_cbu text,
    bank_info text,
    hero_eyebrow text,
    hero_title text,
    hero_description text,
    hero_image_url text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

